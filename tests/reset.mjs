import assert from 'node:assert/strict';
import {resetRecord,restoreRecord} from '../public/reset.js';
const staff={id:1,version:2,name:'テスト',store_id:1,sales_stores:{'2026-09':1},vision:'理想',annual:'年',monthly:'月',challenge:'課題',action:'行動',progress:40,skills:[{date:'2026-09-01',scores:[3,3,3,3,3,3]}],interviews:[{date:'2026-09-01',worry:'悩み',challenge:'課題',feedback:'助言',next:'次'}],sales:[{month:'2026-09',actual:800000,nominated:500000,target:1000000,customers:60},{month:'2026-10',actual:900000,nominated:600000,target:1000000,customers:70},{month:'2026-11',actual:0,nominated:0,target:1200000,customers:0}]};
const original=structuredClone(staff);
const reset=resetRecord(staff,{sales:true,period:'past',month:'2026-10'});
assert.equal(reset.sales[0].actual,0);assert.equal(reset.sales[0].nominated,0);
assert.equal(reset.sales[0].target,1000000);assert.equal(reset.sales[0].customers,60);
assert.deepEqual(reset.sales.slice(1),staff.sales.slice(1));
for(const k of ['interviews','skills','store_id','sales_stores','vision','annual'])assert.deepEqual(reset[k],staff[k]);
assert.deepEqual(staff,original);
assert.deepEqual(restoreRecord(JSON.parse(JSON.stringify(reset))),staff);
const all=resetRecord(staff,{sales:true,targets:true,customers:true,goals:true,period:'all'});
assert.ok(all.sales.every(s=>s.actual===0&&s.nominated===0&&s.target===0&&s.customers===0));
assert.equal(all.action,'');assert.equal(all.progress,0);assert.equal(all.vision,'理想');
assert.deepEqual(restoreRecord(all),staff);
const specific=resetRecord(staff,{targets:true,period:'month',month:'2026-11'});
assert.equal(specific.sales[2].target,0);assert.deepEqual(specific.sales.slice(0,2),staff.sales.slice(0,2));
const edited=structuredClone(reset);edited.sales[0].actual=42;assert.throws(()=>restoreRecord(edited),/編集/);
const moved=structuredClone(reset);moved.store_id=2;moved.interviews.push({date:'2026-10-26'});
const restored=restoreRecord(moved);assert.equal(restored.store_id,2);assert.equal(restored.interviews.length,2);
assert.throws(()=>resetRecord(reset,{sales:true,period:'all'}),/先に/);
assert.equal(resetRecord(staff,{sales:true,period:'month',month:'2020-01'}).reset_backup,undefined);
console.log('PASS: past/current/future boundaries, independent reset categories, persistent undo, conflict protection, interview/skills/transfer preservation, no mutation');
